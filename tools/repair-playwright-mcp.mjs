import { spawn, execSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import {
  PLAYWRIGHT_MCP_PORT,
  PLAYWRIGHT_MCP_URL,
  buildPlaywrightHttpServer,
  buildPlaywrightMcpArgs,
  getPlaywrightMcpCli,
  getPlaywrightOutputDir,
  getPlaywrightUserDataDir,
  getProjectRoot,
  isPlaywrightMcpRunning,
} from './playwright-mcp-shared.mjs';

const projectRoot = getProjectRoot();
const cli = getPlaywrightMcpCli(projectRoot);
const TASK_NAME = 'HundesalonPlaywrightMcp';

function writeJson(filePath, data) {
  mkdirSync(dirname(filePath), { recursive: true });
  writeFileSync(filePath, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
}

function readJson(filePath, fallback = {}) {
  if (!existsSync(filePath)) return structuredClone(fallback);
  try {
    return JSON.parse(readFileSync(filePath, 'utf8'));
  } catch {
    return structuredClone(fallback);
  }
}

function patchPlaywrightServer(target, key) {
  const bucket = target[key] || (target[key] = {});
  bucket.playwright = buildPlaywrightHttpServer();
  return bucket;
}

function configureProjectCursorMcp() {
  const filePath = join(projectRoot, '.cursor', 'mcp.json');
  const data = readJson(filePath, { mcpServers: {} });
  patchPlaywrightServer(data, 'mcpServers');
  writeJson(filePath, data);
  return filePath;
}

function configureUserCursorMcp() {
  const filePath = join(homedir(), '.cursor', 'mcp.json');
  const data = readJson(filePath, { mcpServers: {} });
  patchPlaywrightServer(data, 'mcpServers');
  writeJson(filePath, data);
  return filePath;
}

function configureWorkspaceMcp() {
  const filePath = join(projectRoot, '.vscode', 'mcp.json');
  const data = readJson(filePath, { inputs: [], servers: {} });
  patchPlaywrightServer(data, 'servers');
  writeJson(filePath, data);
  return filePath;
}

function configureVsCodeUserMcp() {
  const filePath = join(homedir(), 'AppData', 'Roaming', 'Code', 'User', 'mcp.json');
  if (!existsSync(filePath)) return null;
  const data = readJson(filePath, { inputs: [], servers: {} });
  patchPlaywrightServer(data, 'servers');
  writeJson(filePath, data);
  return filePath;
}

async function ensureDependencies() {
  if (!existsSync(cli)) {
    console.log('Installing @playwright/mcp…');
    execSync('npm install -D @playwright/mcp playwright', { cwd: projectRoot, stdio: 'inherit' });
  }

  console.log('Ensuring Playwright Chromium + Chrome channel…');
  execSync('npx playwright install chromium', { cwd: projectRoot, stdio: 'inherit' });
  try {
    execSync('npx playwright install chrome', { cwd: projectRoot, stdio: 'inherit' });
  } catch {
    console.log('Chrome channel install skipped (system Chrome is enough if present).');
  }
}

function stopExistingServer() {
  try {
    const out = execSync(
      `powershell -NoProfile -Command "Get-NetTCPConnection -LocalPort ${PLAYWRIGHT_MCP_PORT} -State Listen -ErrorAction SilentlyContinue | Select-Object -ExpandProperty OwningProcess -Unique"`,
      { encoding: 'utf8' }
    );
    const pids = out
      .split(/\r?\n/)
      .map(s => s.trim())
      .filter(Boolean)
      .map(Number)
      .filter(n => Number.isFinite(n) && n > 0);

    for (const pid of pids) {
      console.log(`Stopping old Playwright MCP pid ${pid}…`);
      try {
        process.kill(pid);
      } catch {
        execSync(`taskkill /PID ${pid} /T /F`, { stdio: 'ignore' });
      }
    }
  } catch {
    // nothing listening
  }
}

function ensureHiddenLauncher() {
  const vbsPath = join(homedir(), '.cursor', 'run-hidden.vbs');
  if (!existsSync(vbsPath)) {
    writeFileSync(
      vbsPath,
      'If WScript.Arguments.Count = 0 Then WScript.Quit 1\r\n\r\n' +
        'command = ""\r\n' +
        'For Each argument In WScript.Arguments\r\n' +
        '  command = command & """" & Replace(argument, """", """""") & """ "\r\n' +
        'Next\r\n\r\n' +
        'CreateObject("WScript.Shell").Run command, 0, False\r\n',
      'utf8'
    );
  }
  return vbsPath;
}

function ensureAutostartTask() {
  const serveScript = join(projectRoot, 'tools', 'playwright-mcp-serve.mjs');
  const nodeExe = process.execPath;
  const hiddenVbs = ensureHiddenLauncher();
  const ps1Path = join(homedir(), '.cursor', 'hundesalon-playwright-mcp-autostart.ps1');
  // Launch via wscript + run-hidden.vbs so no console window appears on Windows.
  const ps1 = `# Auto-generated by tools/repair-playwright-mcp.mjs
$taskName = '${TASK_NAME}'
$wscript = Join-Path $env:SystemRoot 'System32\\wscript.exe'
$hiddenVbs = @'
${hiddenVbs}
'@
$nodeExe = @'
${nodeExe}
'@
$serveScript = @'
${serveScript}
'@
$workDir = @'
${projectRoot}
'@
$task = Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
$action = New-ScheduledTaskAction -Execute $wscript -Argument ("\`"{0}\`" \`"{1}\`" \`"{2}\`"" -f $hiddenVbs, $nodeExe, $serveScript) -WorkingDirectory $workDir
$trigger = New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable -RestartCount 3 -RestartInterval (New-TimeSpan -Minutes 1)
$principal = New-ScheduledTaskPrincipal -UserId $env:USERNAME -LogonType Interactive -RunLevel Limited
if ($task) {
  Set-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Settings $settings -Principal $principal | Out-Null
} else {
  Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Settings $settings -Principal $principal -Description "Hundesalon MCP server, hidden background startup" | Out-Null
}
Get-ScheduledTask -TaskName $taskName | Select-Object TaskName,State | Format-List
`;
  writeFileSync(ps1Path, ps1, 'utf8');
  try {
    execSync(`powershell -NoProfile -ExecutionPolicy Bypass -File "${ps1Path}"`, { stdio: 'inherit' });
    console.log(`Autostart task ready (hidden): ${TASK_NAME}`);
  } catch (error) {
    console.warn('Could not register logon autostart task:', error.message);
    // Fallback: Startup folder via hidden launcher (never start "" /MIN — that still shows a window)
    const startupDir = join(homedir(), 'AppData', 'Roaming', 'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup');
    mkdirSync(startupDir, { recursive: true });
    const cmdPath = join(startupDir, 'HundesalonPlaywrightMcp.cmd');
    writeFileSync(
      cmdPath,
      `@echo off\r\nwscript.exe "${hiddenVbs}" "${nodeExe}" "${serveScript}"\r\n`,
      'utf8'
    );
    console.log(`Fallback Startup shortcut written: ${cmdPath}`);
  }
}

async function ensureServerRunning({ restart = false } = {}) {
  if (restart) {
    stopExistingServer();
    await new Promise(resolve => setTimeout(resolve, 800));
  } else if (await isPlaywrightMcpRunning()) {
    console.log(`Playwright MCP already running: ${PLAYWRIGHT_MCP_URL}`);
    return;
  }

  getPlaywrightUserDataDir();
  getPlaywrightOutputDir(projectRoot);

  console.log(`Starting Playwright MCP on port ${PLAYWRIGHT_MCP_PORT}…`);
  const child = spawn(process.execPath, buildPlaywrightMcpArgs(projectRoot), {
    cwd: projectRoot,
    detached: true,
    stdio: 'ignore',
    env: process.env,
    windowsHide: true,
  });
  child.unref();

  for (let attempt = 0; attempt < 30; attempt += 1) {
    await new Promise(resolve => setTimeout(resolve, 400));
    if (await isPlaywrightMcpRunning()) {
      console.log(`Playwright MCP ready: ${PLAYWRIGHT_MCP_URL}`);
      return;
    }
  }

  throw new Error('Playwright MCP HTTP server did not become ready in time.');
}

await ensureDependencies();

const files = [
  configureProjectCursorMcp(),
  configureUserCursorMcp(),
  configureWorkspaceMcp(),
  configureVsCodeUserMcp(),
].filter(Boolean);

for (const filePath of files) {
  console.log(`Updated ${filePath}`);
}

ensureAutostartTask();
await ensureServerRunning({ restart: true });

console.log('\nPlaywright MCP repair complete.');
console.log(`Profile: ${getPlaywrightUserDataDir()}`);
console.log(`Output:  ${getPlaywrightOutputDir(projectRoot)}`);
console.log('Cursor uses HTTP transport (http://localhost:8931/mcp).');
console.log('If tools look stale: Cursor Settings → MCP → toggle Playwright, or Reload Window.');
