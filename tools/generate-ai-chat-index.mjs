import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_PATH = path.join(ROOT, 'knowledge/03_Resources/SendPulse_AI_Agent_Knowledge.md');
const OUTPUT_PATH = path.join(ROOT, 'functions/_generated/ai-chat-knowledge.js');
const MAX_CHUNK_CHARACTERS = 3200;

function cleanHeading(value) {
  return String(value || '')
    .replace(/\s+#+\s*$/, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function inferLocale(title) {
  const match = String(title || '').match(/(?:^|>\s*)(DE|EN|RU|UK)\s*(?:\u2014|-)/i);
  return match ? match[1].toLowerCase() : 'all';
}

function splitOversizedParagraph(paragraph, maxCharacters) {
  const parts = [];
  let remaining = paragraph.trim();

  while (remaining.length > maxCharacters) {
    const window = remaining.slice(0, maxCharacters + 1);
    const boundary = Math.max(window.lastIndexOf('. '), window.lastIndexOf('; '), window.lastIndexOf(', '));
    const splitAt = boundary >= Math.floor(maxCharacters * 0.55) ? boundary + 1 : maxCharacters;
    parts.push(remaining.slice(0, splitAt).trim());
    remaining = remaining.slice(splitAt).trim();
  }

  if (remaining) parts.push(remaining);
  return parts;
}

function chunkSection(section, maxCharacters = MAX_CHUNK_CHARACTERS) {
  const paragraphs = section.body
    .split(/\n{2,}/)
    .map(value => value.replace(/[ \t]+/g, ' ').trim())
    .filter(Boolean)
    .flatMap(value => splitOversizedParagraph(value, maxCharacters));
  const chunks = [];
  let current = '';

  for (const paragraph of paragraphs) {
    const candidate = current ? `${current}\n\n${paragraph}` : paragraph;
    if (candidate.length <= maxCharacters) {
      current = candidate;
      continue;
    }
    if (current) chunks.push(current);
    current = paragraph;
  }
  if (current) chunks.push(current);

  return chunks.map((text, index) => ({
    id: `${section.order}-${index + 1}`,
    locale: inferLocale(section.title),
    title: section.title,
    text,
  }));
}

export function buildAiChatKnowledgeIndex(source) {
  const normalized = String(source || '')
    .replace(/^\uFEFF/, '')
    .replace(/\r\n?/g, '\n')
    .trim();
  const headings = [];
  const sections = [];
  let current = null;

  const flush = () => {
    if (!current) return;
    const body = current.lines.join('\n').trim();
    if (body) sections.push({ ...current, body });
    current = null;
  };

  for (const line of normalized.split('\n')) {
    const heading = /^(#{1,6})\s+(.+?)\s*$/.exec(line);
    if (heading) {
      flush();
      const depth = heading[1].length;
      headings.length = depth - 1;
      headings[depth - 1] = cleanHeading(heading[2]);
      current = {
        order: sections.length + 1,
        title: headings.filter(Boolean).join(' > '),
        lines: [],
      };
      continue;
    }
    if (current) current.lines.push(line);
  }
  flush();

  return sections.flatMap(section => chunkSection(section));
}

export function renderAiChatKnowledgeModule(source) {
  const normalized =
    String(source || '')
      .replace(/^\uFEFF/, '')
      .replace(/\r\n?/g, '\n')
      .trimEnd() + '\n';
  const fingerprint = createHash('sha256').update(normalized).digest('hex');
  const index = buildAiChatKnowledgeIndex(normalized);
  const payload = JSON.stringify(index);
  const content = [
    '// Generated by tools/generate-ai-chat-index.mjs. Do not edit manually.',
    `export const AI_CHAT_KNOWLEDGE_FINGERPRINT = '${fingerprint}';`,
    `export const AI_CHAT_KNOWLEDGE = Object.freeze(${payload}.map(entry => Object.freeze(entry)));`,
    '',
  ].join('\n');

  return { content, fingerprint, index };
}

export function generateAiChatKnowledgeIndex({ check = false } = {}) {
  const source = readFileSync(SOURCE_PATH, 'utf8');
  const generated = renderAiChatKnowledgeModule(source);

  if (check) {
    const existing = readFileSync(OUTPUT_PATH, 'utf8');
    if (existing !== generated.content) {
      throw new Error('AI chat knowledge index is stale. Run npm run knowledge:build.');
    }
    return generated;
  }

  mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  writeFileSync(OUTPUT_PATH, generated.content, 'utf8');
  return generated;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const result = generateAiChatKnowledgeIndex({ check });
  console.log(
    `${check ? 'Verified' : 'Generated'} AI chat knowledge index: ${result.index.length} chunks, sha256:${result.fingerprint}`
  );
}
